#Convert an integer to a floating-point number.
zahl = 10
kommazahl1 = float(zahl)

print("Converted Int value to float is",kommazahl1)
print("Converted type is",type(kommazahl1))

#Convert a floating-point number to an integer.
kommazahl2 = 25.8
convert_to_zahl = int(kommazahl2)

print("Converted Floating value to int is", convert_to_zahl)
print("Converted type is",type(convert_to_zahl))

#Convert an integer to a string.
intvalue = 78
strconversion = str(intvalue)

print("Converted string is",strconversion)
print("Converted type is",type(strconversion))

#Convert a string containing a number to an integer.
strvalue = "99"
intconversion = int(strvalue)

print("Converted integer is",intconversion)
print("Converted type is",type(intconversion))

#Convert an integer to a Boolean
intvalue = 1
boolconversion = bool(intconversion)

print("Converted bool is",boolconversion)
print("Converted type is",type(boolconversion))


